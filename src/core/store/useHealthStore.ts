import { create } from 'zustand';
import { createJSONStorage, persist } from 'zustand/middleware';
import { ENVIRONMENTS } from '@core/config/environments.config';
import { DEMO_CREW, DEMO_DEFAULTS, generateHistory, SCENARIOS } from '@core/simulation';
import type {
  CrewMember,
  EnvironmentId,
  Measurement,
  NewMeasurement,
  ScenarioId,
} from '@core/types';
import { createId } from '@core/utils/id';
import { MS_PER_DAY, startOfUtcDay } from '@core/utils/time';
import { DEFAULT_UNITS, type UnitPreferences } from '@core/utils/units';

export type Language = 'en' | 'tr';

export interface AppSettings {
  language: Language;
  units: UnitPreferences;
  /** Scenario used by "Load demo data". */
  scenario: ScenarioId;
  seed: number;
  /** Days of history generated by "Load demo data" (30–180). */
  historyDays: number;
  /** ISO timestamp of mission day 1, 00:00 — drives the MET clock. */
  missionStart: string;
  /**
   * @deprecated Not read anywhere. The browser-notification switch lives in the routine module's
   * own store (`useNotificationSettings`, ADR-041). Kept so persisted data stays valid.
   */
  notificationsEnabled: boolean;
  /**
   * Load demo data automatically on app start when the device has no data (ADR-009, ADR-044).
   * Default true (the jury never sees an empty app); a real crew turns it off in Settings.
   */
  autoLoadDemo: boolean;
}

export interface LoadDemoOptions {
  scenario?: ScenarioId;
  seed?: number;
  days?: number;
  environment?: EnvironmentId;
  /** Injected for tests; defaults to the real clock. */
  now?: Date;
}

export interface HealthState {
  measurements: Measurement[];
  crew: CrewMember[];
  activeEnvironment: EnvironmentId;
  selectedCrewId: string | null;
  settings: AppSettings;
  /** ISO timestamp of the last demo load; null = never loaded. */
  demoLoadedAt: string | null;

  /** Stores a measurement (id generated if missing) and returns it. */
  addMeasurement: (input: NewMeasurement) => Measurement;
  addMeasurements: (inputs: NewMeasurement[]) => Measurement[];
  removeMeasurement: (id: string) => void;
  setActiveEnvironment: (id: EnvironmentId) => void;
  setSelectedCrew: (id: string | null) => void;
  updateSettings: (patch: Partial<AppSettings>) => void;
  /** Replaces crew + measurements with a deterministic simulated history. */
  loadDemoData: (options?: LoadDemoOptions) => void;
  /**
   * Loads the demo history of a scenario. With `withRecommendedEnvironment` the scenario's
   * recommended environment (SCENARIOS[id].recommendedEnvironment) is applied too; otherwise the
   * active environment stays. Same seed and history length as the current settings.
   */
  applyScenario: (
    scenarioId: ScenarioId,
    options: { withRecommendedEnvironment: boolean; now?: Date },
  ) => void;
  /**
   * Replaces measurements, crew and settings at once (backup restore, ADR-044). Keeps the selected
   * crew member if they still exist, else selects the first one.
   */
  replaceData: (data: {
    measurements: Measurement[];
    crew: CrewMember[];
    settings: AppSettings;
  }) => void;
  /** Clears all data (crew is restored to the demo crew, no measurements). */
  resetAll: () => void;
}

const defaultMissionStart = (): string =>
  new Date(
    startOfUtcDay(new Date()).getTime() - (DEMO_DEFAULTS.days - 1) * MS_PER_DAY,
  ).toISOString();

export const DEFAULT_SETTINGS: AppSettings = {
  language: 'en',
  units: DEFAULT_UNITS,
  scenario: 'mixed_mission',
  seed: DEMO_DEFAULTS.seed,
  historyDays: DEMO_DEFAULTS.days,
  missionStart: defaultMissionStart(),
  notificationsEnabled: false,
  autoLoadDemo: true,
};

const withId = (m: NewMeasurement): Measurement => ({ ...m, id: m.id ?? createId('m') });

const initialData = () => ({
  measurements: [] as Measurement[],
  crew: DEMO_CREW,
  activeEnvironment: 'iss' as EnvironmentId,
  selectedCrewId: DEMO_CREW[0]?.id ?? null,
  settings: DEFAULT_SETTINGS,
  demoLoadedAt: null as string | null,
});

export const STORE_KEY = 'astrovital:health';

/** Persisted schema version. 1 → 2: `settings.autoLoadDemo` (default true). */
export const STORE_VERSION = 2;

/**
 * Upgrades persisted state from an older version. PURE. Unknown shapes are returned as-is
 * (zustand then merges them over the defaults).
 */
export const migrateHealthState = (persisted: unknown, version: number): unknown => {
  if (typeof persisted !== 'object' || persisted === null) return persisted;
  const state = persisted as { settings?: Partial<AppSettings> };
  if (version < 2) {
    return { ...state, settings: { ...DEFAULT_SETTINGS, ...state.settings, autoLoadDemo: true } };
  }
  return state;
};

/**
 * Global shared domain state (persisted to localStorage — offline-first).
 * Module-local UI state (alert acks, XP, ...) belongs in the module's own store.
 */
export const useHealthStore = create<HealthState>()(
  persist(
    (set, get) => ({
      ...initialData(),

      addMeasurement: (input) => {
        const m = withId(input);
        set((s) => ({ measurements: [...s.measurements, m] }));
        return m;
      },

      addMeasurements: (inputs) => {
        const ms = inputs.map(withId);
        set((s) => ({ measurements: [...s.measurements, ...ms] }));
        return ms;
      },

      removeMeasurement: (id) =>
        set((s) => ({ measurements: s.measurements.filter((m) => m.id !== id) })),

      setActiveEnvironment: (id) => set({ activeEnvironment: id }),

      setSelectedCrew: (id) => set({ selectedCrewId: id }),

      updateSettings: (patch) => set((s) => ({ settings: { ...s.settings, ...patch } })),

      loadDemoData: (options = {}) => {
        const { settings, activeEnvironment } = get();
        const now = options.now ?? new Date();
        const scenario = options.scenario ?? settings.scenario;
        const seed = options.seed ?? settings.seed;
        const days = options.days ?? settings.historyDays;
        const envId = options.environment ?? activeEnvironment;
        const measurements = generateHistory({
          seed,
          crew: DEMO_CREW,
          environment: ENVIRONMENTS[envId],
          scenario,
          days,
          end: now,
        });
        const missionStart = new Date(
          startOfUtcDay(now).getTime() - (days - 1) * MS_PER_DAY,
        ).toISOString();
        set((s) => ({
          crew: DEMO_CREW,
          measurements,
          activeEnvironment: envId,
          selectedCrewId: s.selectedCrewId ?? DEMO_CREW[0]?.id ?? null,
          settings: { ...s.settings, scenario, seed, historyDays: days, missionStart },
          demoLoadedAt: now.toISOString(),
        }));
      },

      applyScenario: (scenarioId, { withRecommendedEnvironment, now }) =>
        get().loadDemoData({
          scenario: scenarioId,
          ...(withRecommendedEnvironment
            ? { environment: SCENARIOS[scenarioId].recommendedEnvironment }
            : {}),
          ...(now ? { now } : {}),
        }),

      replaceData: ({ measurements, crew, settings }) =>
        set((s) => ({
          measurements,
          crew,
          settings,
          selectedCrewId: crew.some((c) => c.id === s.selectedCrewId)
            ? s.selectedCrewId
            : (crew[0]?.id ?? null),
          // Restored data counts as loaded: the demo bootstrap must not overwrite it.
          demoLoadedAt: s.demoLoadedAt ?? new Date(0).toISOString(),
        })),

      resetAll: () =>
        set((s) => ({
          ...initialData(),
          // Keep user preferences (language, units, auto-load) across a data reset.
          settings: {
            ...DEFAULT_SETTINGS,
            language: s.settings.language,
            units: s.settings.units,
            autoLoadDemo: s.settings.autoLoadDemo,
          },
        })),
    }),
    {
      name: STORE_KEY,
      version: STORE_VERSION,
      storage: createJSONStorage(() => localStorage),
      migrate: migrateHealthState,
      partialize: (s) => ({
        measurements: s.measurements,
        crew: s.crew,
        activeEnvironment: s.activeEnvironment,
        selectedCrewId: s.selectedCrewId,
        settings: s.settings,
        demoLoadedAt: s.demoLoadedAt,
      }),
    },
  ),
);
